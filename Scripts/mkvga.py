"""Makes View/Vga.c: mkvga.py Assets/Bm437_IBM_VGA_8x16.otb > View/Vga.c

Reads the 8x16 bitmap strike of the IBM VGA font from The Ultimate Oldschool
PC Font Pack and writes its 256 glyphs in CP437 order, one byte a row with
the leftmost pixel in the top bit. Fails if the font lacks a glyph, so the
table never has a hole. Needs fontTools.
"""
import sys

from fontTools.ttLib import TTFont

# CP437's pictures for the control codes, which the cp437 codec decodes as
# the controls themselves. 0x00 is blank.
LOW = [0x0000, 0x263A, 0x263B, 0x2665, 0x2666, 0x2663, 0x2660, 0x2022,
       0x25D8, 0x25CB, 0x25D9, 0x2642, 0x2640, 0x266A, 0x266B, 0x263C,
       0x25BA, 0x25C4, 0x2195, 0x203C, 0x00B6, 0x00A7, 0x25AC, 0x21A8,
       0x2191, 0x2193, 0x2192, 0x2190, 0x221F, 0x2194, 0x25B2, 0x25BC]


def code_point(code):
    if code < 0x20:
        return LOW[code]
    if code == 0x7F:
        return 0x2302
    return ord(bytes([code]).decode('cp437'))


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: mkvga.py FONT.otb > View/Vga.c')
    font = TTFont(sys.argv[1])
    cmap = font.getBestCmap()
    strike = font['EBDT'].strikeData[0]

    rows = []
    for code in range(256):
        cp = code_point(code)
        if cp == 0:
            rows.append((code, cp, bytes(16)))
            continue
        if cp not in cmap:
            sys.exit(f'mkvga.py: {sys.argv[1]} has no U+{cp:04X} for CP437 0x{code:02X}')
        data = strike[cmap[cp]].imageData
        if len(data) != 16:
            sys.exit(f'mkvga.py: U+{cp:04X} is not 8x16')
        rows.append((code, cp, data))

    print('/* SPDX-License-Identifier: CC-BY-SA-4.0 */')
    print('/* The Ultimate Oldschool PC Font Pack, (c) 2016-2020 VileR')
    print(' *   https://int10h.org/oldschool-pc-fonts/')
    print(' */')
    print()
    print('/**')
    print('  Vga - the IBM VGA 8x16 glyphs (Bm437_IBM_VGA_8x16) in CP437 order.')
    print()
    print('  Generated by Scripts/mkvga.py from Assets/Bm437_IBM_VGA_8x16.otb;')
    print('  do not edit.')
    print('*/')
    print()
    print('#include "View/Vga.h"')
    print()
    print('CONST UINT8 gVga[256][VGA_H] = {')
    for code, cp, data in rows:
        hexes = ', '.join(f'0x{b:02x}' for b in data)
        print(f'  [0x{code:02x}] = {{{hexes}}}, // U+{cp:04X}')
    print('};')


if __name__ == '__main__':
    main()
