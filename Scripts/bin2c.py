"""Converts assets to C arrays: bin2c.py NAME=FILE... > assets.c

Each FILE becomes `const unsigned char gOablAssetNAME[]` with its size in
`const size_t gOablAssetNAMESize`. The linker drops the unused ones.
"""
import sys

out = ['/* Generated by Scripts/bin2c.py. */', '#include <stddef.h>']
for arg in sys.argv[1:]:
    name, path = arg.split('=', 1)
    data = open(path, 'rb').read()
    out.append(f'const unsigned char gOablAsset{name}[] = {{')
    for i in range(0, len(data), 24):
        out.append('\t' + ''.join(f'{b},' for b in data[i:i + 24]))
    out.append('};')
    out.append(f'const size_t gOablAsset{name}Size = {len(data)};')
print('\n'.join(out))
